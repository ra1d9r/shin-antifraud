"""Контракт пакетной обработки (брифинг §4.1 и §5.B).

Брифинг §4.1: «Система принимает транзакцию (в режиме реального времени
через API или батч-обработкой)». §5.B: «Интерфейс или API для загрузки
синтетического датасета (100k строк) или симуляции потока транзакций».

## Почему два режима, а не один

Они отвечают на разные вопросы и потому имеют разные ответы.

`POST /predict/batch` — «оцени вот эти операции». Транзакции приходят
от клиента, и он ждёт вердикт по каждой. Ответ — список.

`POST /predict/stream` — «сделай поток и прогони его». Транзакции
порождаются тем же генератором, на котором обучалась модель, и вердикт
по отдельной операции никому не нужен: смысл в том, чтобы система
поработала. Ответ — сводка.

Свести их в один эндпоинт с флагом значило бы получить ручку, у которой
форма ответа зависит от формы запроса.

## Почему поток порождается, а не читается из файла

Датасет генерируется во время сборки образа и тут же удаляется
(`docker/backend.Dockerfile`), чтобы не тащить сто тысяч строк в слои.
На проде CSV нет — а поток нужен именно там. Генератор же лежит в коде
и работает одинаково везде.

## Почему выборка из большого пула, а не маленький датасет

Сначала поток порождался напрямую: нужно триста операций — генерируем
триста. Так делать нельзя, и это видно по наблюдению за дрейфом.

Статистики генератора зависят от объёма: в выборке на триста строк
у клиента две-три операции вместо тридцати, и `transaction_frequency`
расходится с обучающим распределением (PSI до 5.4). Если клиентов
сделать мало, чтобы история набралась, вырождается `account_age_days`
— он постоянен внутри клиента, и триста операций дают девять значений
вместо гладкого распределения (PSI 3.2). Оба конца дают дрейф, которого
на самом деле нет: это артефакт размера выборки, а не сдвиг данных.

Поэтому порождается полноценный датасет на десять тысяч строк
с тем же соотношением операций на клиента, что в обучающем (33:1),
и из него берётся выборка. Дрейф на таком потоке — STABLE, ноль
сдвинутых признаков, худший PSI 0.05.

Побочная выгода: у порождённого потока известна разметка, поэтому сводка
показывает не только распределение решений, но и сколько фрода система
поймала и сколько пропустила — живая проверка качества вместо цифры
из выгруженного артефакта.
"""

from __future__ import annotations

from pydantic import BaseModel, ConfigDict, Field

from app.schemas.prediction import PredictionResponse
from app.schemas.transaction import TransactionRequest

#: Потолок размера партии. Ответ содержит полный разбор каждой операции
#: вместе с вектором признаков и объяснением — около двух килобайт на
#: штуку, так что двести это уже почти полмегабайта.
MAX_BATCH = 200

#: Потолок длины потока. Ответ короткий, ограничение здесь про время:
#: на бесплатном хостинге операция обходится в десятки миллисекунд,
#: и пятьсот штук — это уже полминуты в одном запросе.
MAX_STREAM = 500

#: Дрейфу нужно накопить наблюдения, прежде чем он что-то скажет
#: (`DRIFT_MIN_OBSERVATIONS`). Значение по умолчанию выбрано так, чтобы
#: одного прогона хватило: иначе панель осталась бы пустой и человек
#: решил бы, что она не работает.
DEFAULT_STREAM = 300


class BatchRequest(BaseModel):
    """Партия операций на оценку."""

    model_config = ConfigDict(
        json_schema_extra={
            "example": {
                "transactions": [
                    {
                        "user_id": "user_00042",
                        "amount": 15000.0,
                        "merchant": "Magnum",
                        "country": "KZ",
                        "device_id": "dev_known_1",
                        "ip_address": "85.132.10.55",
                        "latitude": 51.16,
                        "longitude": 71.44,
                        "transaction_frequency": 3,
                        "previous_transaction_amount": 14000.0,
                        "previous_transaction_country": "KZ",
                        "account_age_days": 800,
                    }
                ]
            }
        }
    )

    transactions: list[TransactionRequest] = Field(
        min_length=1,
        max_length=MAX_BATCH,
        description=f"Операции партии, не больше {MAX_BATCH} за раз",
    )


class BatchSummary(BaseModel):
    """Что получилось на партии целиком."""

    processed: int
    decisions: dict[str, int] = Field(description="Сколько операций в каждом решении")
    average_risk_score: float
    raised_by_rules: int = Field(
        description="Операции, где политики подняли оценку выше модели"
    )
    triggered_rules: dict[str, int] = Field(
        description="Сколько раз сработала каждая политика"
    )
    processing_ms: float


class BatchResponse(BaseModel):
    """Вердикты по партии и сводка по ней."""

    summary: BatchSummary
    replayed: int = Field(
        description=(
            "Сколько операций обслужено повтором вместо обработки. "
            "Идемпотентность здесь та же, что у одиночного `/predict`: "
            "повторно отправленная партия не удвоит ни историю, ни профили."
        )
    )
    results: list[PredictionResponse]


class StreamRequest(BaseModel):
    """Задание на порождение потока."""

    count: int = Field(
        default=DEFAULT_STREAM,
        ge=1,
        le=MAX_STREAM,
        description=f"Сколько операций породить и прогнать, не больше {MAX_STREAM}",
    )
    seed: int | None = Field(
        default=None,
        ge=0,
        description=(
            "Зерно генератора. По умолчанию каждый прогон даёт новый поток: "
            "с постоянным зерном два нажатия подряд прислали бы те же "
            "`transaction_id`, и в истории операций они выглядели бы "
            "дубликатами. Задайте зерно явно, когда нужен воспроизводимый "
            "прогон — использованное значение возвращается в сводке."
        ),
    )


class StreamSummary(BaseModel):
    """Итог прогона потока.

    Разметка потока известна, поэтому качество считается прямо здесь,
    а не берётся из выгруженной аналитики.
    """

    requested: int
    processed: int
    seed: int = Field(description="Зерно выборки: с ним прогон воспроизводится")
    pool_rows: int = Field(
        description="Размер датасета, из которого взята выборка"
    )

    decisions: dict[str, int]
    average_risk_score: float
    raised_by_rules: int
    triggered_rules: dict[str, int]

    fraud_in_stream: int = Field(description="Мошеннических операций по разметке генератора")
    fraud_stopped: int = Field(description="Из них не пропущено: BLOCK или CHALLENGE")
    fraud_missed: int = Field(description="Из них прошло с решением APPROVE")
    false_positives: int = Field(
        description="Добросовестные операции, которые система задержала"
    )

    processing_ms: float
