"""Язык ответов API (брифинг §6, Положение §1.6).

## Зачем это в backend, а не только в интерфейсе

Интерфейс переведён на три языка, но часть текста он не сочиняет,
а получает готовым: описания признаков, пояснения к решениям,
описания демонстрационных сценариев. По принципу ТЗ §11 клиент
ничего не вычисляет сам — значит и переводить эти строки у себя
он не должен, иначе появится вторая копия формулировок, которая
однажды разойдётся с первой. Ровно так уже случилось с пояснением
к решению: отчёт и интерфейс описывали одно решение двумя разными
фразами (см. `Decision.meaning_in`).

Поэтому язык — параметр запроса, а не свойство клиента. Побочная
польза: переводы достаются и тем, кто дёргает API без нашего
интерфейса.

## Почему `Text`, а не три отдельных поля

Три языка лежат в одном объекте, и все три обязательны. Забыть
перевод структурно нельзя: пропуск — не пустая строка, которая
тихо покажется пользователю, а ошибка конструктора. Отдельные
поля `description_kk`, `description_en` такой гарантии не дают.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Literal, get_args

Language = Literal["ru", "kk", "en"]

LANGUAGES: tuple[Language, ...] = get_args(Language)

#: Русский — язык, на котором написан проект, и язык по умолчанию
#: для запроса без параметра. Положение §1.6 называет рабочими
#: языками хакатона русский и казахский.
DEFAULT_LANGUAGE: Language = "ru"


@dataclass(frozen=True, slots=True)
class Text:
    """Одна строка на трёх языках.

    Пустой перевод запрещён: строка, которой нет, должна ломать
    сборку приложения, а не показываться пользователю пустым местом.
    """

    ru: str
    kk: str
    en: str

    def __post_init__(self) -> None:
        for language in LANGUAGES:
            if not getattr(self, language).strip():
                raise ValueError(f"перевод на «{language}» пуст: {self.ru!r}")

    def get(self, language: Language) -> str:
        """Текст на запрошенном языке."""
        return str(getattr(self, language))
