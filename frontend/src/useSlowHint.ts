import { useEffect, useState } from 'react'

/**
 * Через сколько молчание стоит объяснить.
 *
 * Обычный ответ приходит за десятки миллисекунд, так что четыре секунды —
 * уже не «медленно», а «что-то происходит». Показывать подсказку сразу
 * было бы вредно: она мелькала бы на каждом нормальном запросе.
 */
export const SLOW_HINT_AFTER_MS = 4_000

/**
 * Объяснение долгой паузы. Одно на оба экрана, чтобы формулировки
 * не разошлись — теперь ключом, а текст берётся из словаря.
 */
export const WAKE_UP_HINT_KEY = 'api.wakeUp' as const

/**
 * Признак затянувшегося ожидания.
 *
 * Нужен из-за бесплатного хостинга: сервис засыпает после простоя, и первое
 * обращение сначала будит контейнер — это до минуты. Без объяснения такая
 * пауза неотличима от зависшего интерфейса, и человек уходит, решив,
 * что демонстрация сломана.
 *
 * Возвращает `true`, пока ожидание длится дольше `delayMs`. Сбрасывается,
 * как только `active` становится `false`.
 */
export function useSlowHint(active: boolean, delayMs: number = SLOW_HINT_AFTER_MS): boolean {
  const [slow, setSlow] = useState(false)

  useEffect(() => {
    if (!active) return

    const timer = setTimeout(() => setSlow(true), delayMs)
    // Сброс в очистке, а не в теле эффекта: синхронный setState при каждом
    // прогоне вызывал бы каскад перерисовок, и правило react-hooks об этом
    // справедливо предупреждает.
    return () => {
      clearTimeout(timer)
      setSlow(false)
    }
  }, [active, delayMs])

  // `active &&` страхует от подвисшего `true`: подсказка не должна мелькать
  // на следующем, уже быстром запросе.
  return active && slow
}
