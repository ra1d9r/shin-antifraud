/**
 * Арифметика графика компромисса.
 *
 * Вынесена из компонента: попасть курсором в порог — это перевод между
 * тремя системами координат (экранные пиксели, viewBox, шкала 0..100),
 * и ошибиться там легче всего незаметно.
 */

/**
 * Порог под курсором.
 *
 * Накладка, которая ловит мышь, занимает ровно область рисования —
 * от порога 0 до порога 100. Поэтому пересчёт простой: доля по ширине
 * накладки и есть порог, и ни viewBox, ни отступы сюда не входят.
 * Так задумано: пока накладка совпадает с областью, эта функция
 * не зависит от размеров картинки вовсе.
 *
 * @param pointerX положение курсора в пикселях от левого края накладки
 * @param elementWidth ширина накладки на экране
 */
export function thresholdAtPointer(pointerX: number, elementWidth: number): number | null {
  // Ширина ноль бывает у скрытой вкладки: делить на неё нельзя,
  // а показывать подсказку невидимому графику незачем.
  if (!Number.isFinite(elementWidth) || elementWidth <= 0) return null
  if (!Number.isFinite(pointerX)) return null

  const raw = Math.round((pointerX / elementWidth) * 100)

  // Зажим обязателен: у самого края округление даёт 101 или −1, точки
  // с таким порогом на кривой нет, и подсказка исчезала бы ровно там,
  // где по ней и ведут.
  return Math.min(100, Math.max(0, raw))
}

/**
 * Куда положить подсказку, чтобы она не уехала за край.
 *
 * У правого края она переезжает на другую сторону засечки: иначе
 * на порогах под сотню половина чисел оказывалась бы за картинкой.
 */
export function readoutX(markX: number, boxWidth: number, viewWidth: number, gap = 10): number {
  const flipped = markX + boxWidth + gap + 4 > viewWidth
  return flipped ? markX - boxWidth - gap : markX + gap
}
