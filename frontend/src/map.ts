/**
 * Проекция координат на карту (брифинг §6).
 *
 * Равнопромежуточная цилиндрическая проекция: широта и долгота ложатся
 * на прямоугольник линейно. Она искажает площади у полюсов, но здесь
 * это не важно — точки стоят между 24° ю.ш. и 57° с.ш., и ни одна
 * не попадает в зону заметного искажения.
 *
 * Вынесено отдельным модулем, чтобы арифметику можно было проверить
 * тестом: ошибка в знаке долготы переносит операцию на другое
 * полушарие, и заметить это на глаз почти невозможно.
 */

/** Границы холста карты в его собственных координатах. */
export interface MapBox {
  width: number
  height: number
}

/**
 * Географическая точка -> точка холста.
 *
 * Долгота растёт на восток, поэтому по X всё просто. Широта растёт
 * на север, а Y в SVG — вниз, поэтому её приходится перевернуть.
 * Именно здесь легче всего ошибиться, и именно это проверяет тест.
 */
export function project(
  latitude: number,
  longitude: number,
  box: MapBox,
): { x: number; y: number } {
  const x = ((longitude + 180) / 360) * box.width
  const y = ((90 - latitude) / 180) * box.height
  return { x, y }
}

/**
 * Радиус кружка по числу операций.
 *
 * Корень, а не линейная зависимость: площадь круга растёт как квадрат
 * радиуса, и при линейном радиусе страна с шестьюдесятью тысячами
 * операций закрыла бы собой половину карты. Глаз сравнивает площади,
 * поэтому по площади и масштабируем.
 */
export function radius(rows: number, maxRows: number, min = 4, max = 26): number {
  if (maxRows <= 0 || rows <= 0) return min
  const share = Math.sqrt(rows) / Math.sqrt(maxRows)
  return min + (max - min) * share
}

/**
 * Цвет точки по доле фрода.
 *
 * Три ступени, а не непрерывный градиент: на карте с тридцатью точками
 * оттенок читается хуже, чем категория, и аналитику нужен ответ
 * «тут плохо или нет», а не точное значение — оно есть в подсказке.
 */
export type RiskTone = 'low' | 'medium' | 'high'

export function tone(fraudShare: number): RiskTone {
  if (fraudShare >= 0.5) return 'high'
  if (fraudShare >= 0.1) return 'medium'
  return 'low'
}

/**
 * Сдвиг подписи, чтобы она не легла на соседнюю точку.
 *
 * Подпись ставится справа от кружка, а у самого правого края карты —
 * слева: иначе она уезжает за границу и обрезается.
 */
export function labelAnchor(x: number, box: MapBox): { dx: number; anchor: 'start' | 'end' } {
  const nearRightEdge = x > box.width - 60
  return nearRightEdge ? { dx: -6, anchor: 'end' } : { dx: 6, anchor: 'start' }
}
