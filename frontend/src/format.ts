/**
 * Форматирование чисел, денег и дат для всех панелей.
 *
 * Вынесено, когда `Math.round(value).toLocaleString('ru-RU')` разошлось
 * по трём файлам, а `value.toLocaleString('ru-RU')` — ещё по трём. Копии
 * начали бы расходиться в мелочах: где-то остались бы копейки, где-то нет,
 * и одна и та же сумма выглядела бы на соседних панелях по-разному.
 *
 * ## Почему локаль стала параметром
 *
 * Сначала здесь было жёстко `'ru-RU'`. В английском режиме это выглядело
 * как недоделка: заголовки по-английски, а «58 521» и «21.09.2026»
 * по-русски. Английский разделяет разряды запятой и пишет дату
 * по-своему; русский и казахский совпадают, но полагаться на это
 * значило бы закрепить совпадение, которое ничем не гарантировано.
 *
 * Функции принимают локаль явно, а не читают её из глобального
 * состояния: глобал не заставил бы компонент перерисоваться при смене
 * языка, и числа остались бы в прежнем формате до следующего действия.
 * Компоненты берут связанные с языком версии через `useFormat`.
 */

import type { Language } from './i18n'

/**
 * Локаль форматирования для каждого языка интерфейса.
 *
 * Казахский намеренно отображается в `ru-RU`, а не в `kk-KZ`. В Казахстане
 * разряды разделяют пробелом и дату пишут как 21.09.2026 — так же, как
 * по-русски. А данные ICU у казахской локали разнятся от среды к среде:
 * Node отдаёт «99 360», браузер для `kk` — «99,360» и дату «2026-09-21».
 * Зависеть от того, чей ICU достался пользователю, нельзя: одно и то же
 * число выглядело бы по-разному на разных машинах.
 *
 * Поймано это живой проверкой, а не тестом: первый тест сравнивал
 * казахский с русским и в Node проходил. Теперь он проверяет само
 * свойство — разряды через пробел, а не запятую.
 */
const LOCALES: Record<Language, string> = {
  ru: 'ru-RU',
  kk: 'ru-RU',
  en: 'en-US',
}

/**
 * Валюта датасета.
 *
 * Брифинг ведёт счёт в тенге: «850 000 ₸», «средний чек: 15 000 ₸»
 * (§10). Генератор выдаёт суммы без единицы, и без подписи на экране
 * стояли голые числа — жюри, сверяющее их с примером из кейса, не
 * понимало бы, те же это деньги или другие.
 */
export const CURRENCY = '₸'

export function localeOf(language: Language): string {
  return LOCALES[language] ?? LOCALES.ru
}

/** Количество: разряды через разделитель локали, дробной части нет по смыслу. */
export function formatCount(value: number, language: Language = 'ru'): string {
  if (!Number.isFinite(value)) return '—'
  return value.toLocaleString(localeOf(language))
}

/**
 * Сумма денег с валютой.
 *
 * Округляется до целого: на дашборде читают порядок величины, а копейки
 * в шестизначном числе только мешают его увидеть.
 */
export function formatMoney(value: number, language: Language = 'ru'): string {
  if (!Number.isFinite(value)) return '—'
  return `${Math.round(value).toLocaleString(localeOf(language))} ${CURRENCY}`
}

/**
 * Дата и время.
 *
 * Показывается, когда выгружена аналитика и когда подобраны пороги:
 * по этим меткам видно, насколько свежие числа на экране.
 */
export function formatDateTime(value: string, language: Language = 'ru'): string {
  const date = new Date(value)
  if (Number.isNaN(date.getTime())) return '—'
  return date.toLocaleString(localeOf(language))
}
